# Embedding stripping
# ═════════════════════════════════════════════════════════════════════════════

class TestEmbeddingStripping:
    """verse_type and vector_embedding are mutually exclusive on every chunk."""

    def test_no_verse_chunk_has_embedding(self, indexed, config, opensearch_client):
        verses = _verse_chunks_for(opensearch_client, config.OPENSEARCH_INDEX_NAME, _ALPHA_DOC_ID)
        assert len(verses) > 0
        for doc in verses:
            assert "vector_embedding" not in doc["_source"], (
                f"Verse chunk {doc['_id']} must not carry vector_embedding"
            )

    def test_all_para_chunks_have_embedding(self, indexed, config, opensearch_client):
        paras = _para_chunks_for(opensearch_client, config.OPENSEARCH_INDEX_NAME, _ALPHA_DOC_ID)
        assert len(paras) > 0
        for doc in paras:
            src = doc["_source"]
            assert "vector_embedding" in src
            assert isinstance(src["vector_embedding"], list)
            assert len(src["vector_embedding"]) > 0

    def test_no_chunk_has_both_verse_type_and_embedding(self, indexed, config, opensearch_client):
        """Structural invariant: verse_type and vector_embedding never coexist."""
        hits = _raw_query(opensearch_client, config.OPENSEARCH_INDEX_NAME, {
            "bool": {
                "must": [
                    {"exists": {"field": "verse_type"}},
                    {"exists": {"field": "vector_embedding"}},
                ]
            }
        })
        assert len(hits) == 0, (
            f"{len(hits)} chunk(s) illegally carry both verse_type and vector_embedding"
        )

    def test_para_plus_verse_equals_total(self, indexed, config, opensearch_client):
        """Paragraph count + verse count = total chunk count (no overlap, no gap)."""
        index_name = config.OPENSEARCH_INDEX_NAME
        all_docs   = _docs_for(opensearch_client, index_name, _ALPHA_DOC_ID)
        para_docs  = _para_chunks_for(opensearch_client, index_name, _ALPHA_DOC_ID)
        verse_docs = _verse_chunks_for(opensearch_client, index_name, _ALPHA_DOC_ID)
        assert len(para_docs) + len(verse_docs) == len(all_docs)


