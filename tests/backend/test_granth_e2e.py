def _raw_query(opensearch_client, index_name, query, size=500):
    """Execute a raw OpenSearch query; return the list of hits."""
    response = opensearch_client.search(
        index=index_name,
        body={"size": size, "query": query},
    )
    return response["hits"]["hits"]


def _docs_for(opensearch_client, index_name, doc_id):
    """All indexed chunks for a given document_id."""
    return _raw_query(
        opensearch_client, index_name,
        {"term": {"document_id": doc_id}},
    )


def _verse_chunks_for(opensearch_client, index_name, doc_id):
    """Chunks that have a verse_type field (verse-indexed)."""
    return _raw_query(opensearch_client, index_name, {
        "bool": {
            "must": [
                {"term":   {"document_id": doc_id}},
                {"exists": {"field": "verse_type"}},
            ]
        }
    })


def _para_chunks_for(opensearch_client, index_name, doc_id):
    """Chunks that have a vector_embedding field (paragraph-indexed)."""
    return _raw_query(opensearch_client, index_name, {
        "bool": {
            "must": [
                {"term":   {"document_id": doc_id}},
                {"exists": {"field": "vector_embedding"}},
            ]
        }
    })


