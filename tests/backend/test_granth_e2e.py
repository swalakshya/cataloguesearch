def indexed(config, opensearch_client):
    """
    Index alpha (flat) and beta (sub-sectioned) via Discovery.crawl().

    Temp layout (mirrors the real production layout):
        <base>/data/pdfs/
            alpha.pdf            (13 blank pages — needed by get_scan_config)
            beta.pdf             (13 blank pages)
            scan_config.json     (ocr_engine=llm, ignore_bookmarks, sub_sections for beta)
            config.json          (language=hi, category=Granth)
            alpha_config.json    (Granth=Alpha Granth)
            beta_config.json     (Granth=Beta Granth)
        <base>/data/ocr/
            alpha/page_0001.json … page_0013.json   (copied from tests/data)
            beta/page_0001.json  … page_0013.json
        <base>/data/texts/
        <base>/crawl_state.db

    config.settings()["crawler"] paths are updated so Discovery uses the temp
    dirs, then restored on teardown.

    Doc IDs are auto-generated by SingleFileProcessor; after crawling they are
    discovered from the index and stored in module globals so all test
    assertions can reference them without knowing the UUID values.

    Starts from a clean slate (all three indices deleted + recreated) and
    ends in a clean slate (all three indices deleted on teardown).
    """
    global _ALPHA_DOC_ID, _BETA_A_DOC_ID, _BETA_B_DOC_ID

    all_indices = [
        config.OPENSEARCH_INDEX_NAME,
        config.OPENSEARCH_METADATA_INDEX_NAME,
    ]

    # ── clean slate ───────────────────────────────────────────────────────────
    for idx in all_indices:
        opensearch_client.indices.delete(index=idx, ignore=[400, 404])
    create_indices_if_not_exists(config, opensearch_client)

    # ── temp directory layout ─────────────────────────────────────────────────
    base_dir = tempfile.mkdtemp(prefix="granth_e2e_")
    pdf_dir  = os.path.join(base_dir, "data", "pdfs")
    ocr_dir  = os.path.join(base_dir, "data", "ocr")
    text_dir = os.path.join(base_dir, "data", "texts")
    db_path  = os.path.join(base_dir, "crawl_state.db")

    os.makedirs(pdf_dir)
    os.makedirs(os.path.join(ocr_dir, "alpha"))
    os.makedirs(os.path.join(ocr_dir, "beta"))
    os.makedirs(text_dir)

    # ── create minimal PDFs (get_scan_config calls fitz.open) ────────────────
    for name in ("alpha", "beta"):
        doc = fitz.open()
        for _ in range(13):
            doc.new_page()
        doc.save(os.path.join(pdf_dir, f"{name}.pdf"))
        doc.close()

    # ── copy pre-built OCR data into the expected locations ───────────────────
    for name, src_dir in (("alpha", _ALPHA_DIR), ("beta", _BETA_DIR)):
        dst_dir = os.path.join(ocr_dir, name)
        for fname in os.listdir(src_dir):
            if fname.startswith("page_") and fname.endswith(".json"):
                shutil.copy(os.path.join(src_dir, fname), os.path.join(dst_dir, fname))

    # ── write scan_config.json ────────────────────────────────────────────────
    write_config_file(os.path.join(pdf_dir, "scan_config.json"), {
        "default": {
            "chunk_strategy":   "llm",
            "ocr_engine":       "llm",
            "ignore_bookmarks": True,
            "stop_words":       ["विशेष"],
            "question_prefix":  ["प्रश्न"],
            "answer_prefix":    ["उत्तर"],
            "verses":           ["hindi_verse", "prakrit_verse", "sanskrit_verse"],
            "typo_list":        [],
        },
        "alpha": {
            "start_page": 1,
            "end_page":   13,
        },
        "beta": {
            "sub_sections": [
                {"field": _BETA_SEC_FIELD, "name": _BETA_SEC_A_NAME,
                 "start_page": 1, "end_page": 7},
                {"field": _BETA_SEC_FIELD, "name": _BETA_SEC_B_NAME,
                 "start_page": 8, "end_page": 13},
            ],
        },
    })

    # ── write config.json and per-file *_config.json ──────────────────────────
    write_config_file(os.path.join(pdf_dir, "config.json"),
                      {"language": "hi", "category": "Granth"})
    write_config_file(os.path.join(pdf_dir, "alpha_config.json"),
                      {"Name": "Alpha Granth"})
    write_config_file(os.path.join(pdf_dir, "beta_config.json"),
                      {"Name": "Beta Granth"})

    # ── point config to the temp dirs (same as common.setup()) ───────────────
    crawler = config.settings()["crawler"]
    orig = {k: crawler[k] for k in
            ("base_pdf_path", "base_text_path", "base_ocr_path", "sqlite_db_path")}
    crawler["base_pdf_path"]  = pdf_dir
    crawler["base_text_path"] = text_dir
    crawler["base_ocr_path"]  = ocr_dir
    crawler["sqlite_db_path"] = db_path

    try:
        discovery = Discovery(
            config,
            IndexGenerator(config, opensearch_client),
            IndexState(config.SQLITE_DB_PATH),
        )
        # process=False because OCR files are already pre-populated
        discovery.crawl(process=False, index=True)

        opensearch_client.indices.refresh(index=config.OPENSEARCH_INDEX_NAME)

        # ── discover doc IDs from the index (no hardcoding needed) ───────────
        all_hits = opensearch_client.search(
            index=config.OPENSEARCH_INDEX_NAME,
            body={"size": 500, "query": {"match_all": {}}},
        )["hits"]["hits"]

        for hit in all_hits:
            meta = hit["_source"].get("metadata", {})
            doc_id = hit["_source"]["document_id"]
            sub = meta.get("sub_section") or {}
            if meta.get("Name") == "Alpha Granth":
                _ALPHA_DOC_ID = doc_id
            elif sub.get("name") == _BETA_SEC_A_NAME:
                _BETA_A_DOC_ID = doc_id
            elif sub.get("name") == _BETA_SEC_B_NAME:
                _BETA_B_DOC_ID = doc_id

        yield {}

    finally:
        # ── restore config paths ──────────────────────────────────────────────
        crawler.update(orig)
        shutil.rmtree(base_dir, ignore_errors=True)
        for idx in all_indices:
            opensearch_client.indices.delete(index=idx, ignore=[400, 404])


